import nodemailer from 'nodemailer';
import { db } from '../db/database.js';
import { config } from '../config/index.js';

// Transporter configuration (lazy initialized)
let transporter = null;
if (config.smtp.host && config.smtp.user && config.smtp.pass) {
  transporter = nodemailer.createTransport({
    host: config.smtp.host,
    port: config.smtp.port,
    secure: config.smtp.secure,
    auth: {
      user: config.smtp.user,
      pass: config.smtp.pass
    }
  });
}

export async function submitContactForm(req, res) {
  try {
    const { name, email, subject, message } = req.sanitizedData;
    const clientIp = req.headers['x-forwarded-for'] || req.socket.remoteAddress || '127.0.0.1';
    const userAgent = req.headers['user-agent'] || 'Unknown Browser';

    // 1. Persist to database
    const savedMsg = db.messages.create({
      name,
      email,
      subject,
      message,
      ip: clientIp,
      userAgent
    });

    console.log(`[CONTACT RECEIVED] New inquiry from ${name} <${email}>: "${subject}" [ID: ${savedMsg.id}]`);

    // 2. Dispatch Email notification if SMTP is configured
    let emailSent = false;
    if (transporter) {
      try {
        await transporter.sendMail({
          from: `"Portfolio Contact Form" <${config.smtp.user}>`,
          to: config.smtp.receiverEmail,
          replyTo: email,
          subject: `[Portfolio Inquiry] ${subject} - from ${name}`,
          text: `You have received a new contact submission from your portfolio:\n\nName: ${name}\nEmail: ${email}\nSubject: ${subject}\nDate: ${new Date().toLocaleString()}\n\nMessage:\n${message}\n\n---\nView this in your Admin Dashboard.`,
          html: `
            <div style="font-family: Arial, sans-serif; max-width: 600px; padding: 20px; border: 1px solid #e0e0e0; border-radius: 8px;">
              <h2 style="color: #00d4ff; margin-top: 0;">New Portfolio Inquiry</h2>
              <p><strong>From:</strong> ${name} (&lt;<a href="mailto:${email}">${email}</a>&gt;)</p>
              <p><strong>Subject:</strong> ${subject}</p>
              <p><strong>Received:</strong> ${new Date().toLocaleString()}</p>
              <hr style="border: 0; border-top: 1px solid #eee; margin: 20px 0;" />
              <div style="background: #f9f9f9; padding: 15px; border-radius: 6px; white-space: pre-wrap; font-size: 14px; color: #333;">${message}</div>
              <p style="margin-top: 20px; font-size: 12px; color: #888;">This email was automatically generated by your full-stack portfolio backend.</p>
            </div>
          `
        });
        emailSent = true;
      } catch (mailErr) {
        console.error('[SMTP ERROR] Failed to send email alert:', mailErr.message);
      }
    }

    return res.status(201).json({
      success: true,
      message: 'Thank you! Your message has been safely received. Rahul will get back to you promptly.',
      data: {
        id: savedMsg.id,
        createdAt: savedMsg.createdAt,
        emailNotificationDispatched: emailSent
      }
    });
  } catch (err) {
    console.error('[CONTACT CONTROLLER ERROR]', err);
    return res.status(500).json({
      success: false,
      error: 'An internal server error occurred while processing your message. Please reach out directly via email.'
    });
  }
}

